'use strict';
// node test-retirement.cjs [--ui]; browser checks use an isolated career.
const assert = require('node:assert/strict');
const G = require('./engine.js');
const copy = s => JSON.parse(JSON.stringify(s));
const s = G.newGame(42), own = G.roster(s);
const p = own.find(p => p.pos === 'DF'), waiting = own.find(p => p.pos === 'FW');
const young = own.find(p => p.pos === 'MF'), keeper = own.find(p => p.pos === 'GK');
p.age = waiting.age = keeper.age = 35; young.age = 34;
own.forEach(p => { p.contract = s.season + 5; });
const before = {budget:s.budget, salary:p.salary, contract:p.contract};
G.upgradeSave(s);
assert.equal(p.retirementRequestSeason, s.season);
assert.equal(young.retirementRequestSeason, undefined);
assert.equal(G.player(s, p.id), p);
assert.equal(p.club, 0); assert(!p.retired);
assert.deepEqual({budget:s.budget, salary:p.salary, contract:p.contract}, before);
const requested = copy(s);
G.upgradeSave(s); assert.deepEqual(s, requested, 'reload must not duplicate requests or news');
assert(G.validSave(copy(s)));
assert(!G.resolveRetirement(s, own.find(p => p.age < 35).id, true).ok);
assert(!G.resolveRetirement(s, s.players.find(p => p.club === 1).id, true).ok);
assert(!G.resolveRetirement(s, p.id, 'yes').ok);
const shortSquad = copy(s);
G.roster(shortSquad).filter(p => p.pos === 'GK' && p.id !== keeper.id).forEach(p => { p.injury = 1; });
assert(!G.resolveRetirement(shortSquad, keeper.id, true).ok, 'keep an available goalkeeper');
G.startMatch(s);
const inMatch = JSON.stringify(s);
assert(!G.resolveRetirement(s, p.id, true).ok);
assert(!G.resolveRetirement(s, p.id, false).ok);
assert.equal(JSON.stringify(s), inMatch, 'match rejection must not mutate state');
s.pending = null;
assert(G.resolveRetirement(s, p.id, false).ok);
assert.equal(p.retirementRequestSeason, undefined);
assert.equal(p.retirementDeferredSeason, s.season);
G.upgradeSave(s); assert.equal(p.retirementRequestSeason, undefined);
assert.equal(p.contract, before.contract, 'deferral is not a contract renewal');
const pendingSeason = waiting.retirementRequestSeason;
s.week = s.totalWeeks; assert(G.nextSeason(s));
assert.equal(p.retirementRequestSeason, s.season, 'request again next season after deferral');
assert.equal(waiting.retirementRequestSeason, pendingSeason, 'unanswered request survives season change');
assert.equal(waiting.club, 0); assert(!waiting.retired);
assert.equal(young.retirementRequestSeason, s.season, 'turning 35 creates a request');
assert(G.validSave(copy(s)));

const loanState = copy(s), loanPlayer = G.player(loanState, p.id);
loanState.budget = 10000;
const offer = G.loanOffers(loanState, p.id)[0];
assert(offer); assert(G.loanOut(loanState, p.id, offer.club).ok);
assert.equal(loanPlayer.retirementRequestSeason, undefined);
assert(!G.resolveRetirement(loanState, p.id, true).ok);
G.upgradeSave(loanState);
assert.equal(loanPlayer.retirementRequestSeason, undefined);
assert(G.validSave(copy(loanState)));

const invalid = copy(s);
G.player(invalid, p.id).retirementRequestSeason = s.season + 1;
assert(!G.validSave(invalid));
G.player(invalid, p.id).retirementRequestSeason = '2035';
assert(!G.validSave(invalid));

p.history.push({season:s.season-1,club:0,appearances:20,goals:3,minutes:1800});
p.goals = 2; p.appearances = 4;
const history = copy(p.history), wages = G.payroll(s), budget = s.budget;
s.captain = p.id; s.watch.push(p.id); s.scouting.push({player:p.id,remaining:1});
s.transferList.push(p.id); p.transferListed = true;
s.incoming.push({player:p.id,club:1,cash:1,id:`${s.season}-0`});
assert(G.resolveRetirement(s, p.id, true).ok);
assert.equal(p.retired, true); assert.equal(p.club, -1);
assert(!s.players.includes(p)); assert(s.retiredPlayers.includes(p));
assert.equal(G.player(s, p.id), p, 'historical references still resolve');
assert.deepEqual(p.history, history); assert.equal(p.goals, 2); assert.equal(p.appearances, 4);
assert.equal(s.budget, budget); assert.equal(G.payroll(s), Math.round((wages-p.salary)*100)/100);
assert(!s.clubs[0].lineup.includes(p.id)); assert.equal(s.captain, null);
assert(!s.watch.includes(p.id)); assert(!s.scouting.some(r => r.player === p.id));
assert(!s.transferList.includes(p.id)); assert(!s.incoming.some(o => o.player === p.id));
assert(!G.filterPlayers(s).some(q => q.id === p.id));
assert(!G.deal(s, p.id, 0).ok); assert(!G.scout(s, p.id).ok);
assert(!G.resolveRetirement(s, p.id, true).ok, 'cannot approve twice');
assert(G.validSave(copy(s)));
console.log('PASS: requests, approval, deferral, season rollover, loans, roster protection, records and save validation.');

if (process.argv.includes('--ui')) runUI().catch(e => { console.error(e); process.exitCode = 1; });
async function runUI() {
  const fs = require('node:fs'), http = require('node:http'), path = require('node:path');
  const {chromium} = require('playwright');
  const server = http.createServer((req,res) => {
    const file = req.url === '/' ? 'index.html' : req.url.slice(1);
    if (!['index.html','world.js','engine.js','manager.js','app.js','style.css'].includes(file)) return res.writeHead(404).end();
    res.setHeader('Content-Type', file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : 'text/html');
    res.end(fs.readFileSync(path.join(__dirname,file)));
  });
  await new Promise(r => server.listen(0,'127.0.0.1',r));
  let browser;
  try {
    browser = await chromium.launch({headless:true,channel:'msedge'});
    const tab = await browser.newPage({viewport:{width:1440,height:1080}}), errors = [];
    tab.on('pageerror',e => errors.push(e.message));
    await tab.goto(`http://127.0.0.1:${server.address().port}`);
    await tab.waitForSelector('[data-start-career]');
    const id = await tab.evaluate(() => {
      state = G.newGame(42); state.careerSelected = true;
      G.roster(state).forEach(p => { p.contract = state.season+5; });
      const p = G.roster(state).find(p => p.pos === 'DF'); p.age = 35;
      G.upgradeSave(state); closeModal(); page = 'overview'; render(); return p.id;
    });
    await tab.locator(`[data-retirement="${id}"]`).click();
    assert(await tab.locator(`[data-retirement-approve="${id}"]`).isEnabled());
    fs.mkdirSync('test-artifacts',{recursive:true});
    await tab.screenshot({path:'test-artifacts/retirement-desktop.png',fullPage:true});
    await tab.setViewportSize({width:390,height:844});
    assert(await tab.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await tab.screenshot({path:'test-artifacts/retirement-mobile.png',fullPage:true});
    await tab.locator(`[data-retirement-defer="${id}"]`).click();
    assert.equal(await tab.locator(`[data-retirement="${id}"]`).count(), 0);
    await tab.evaluate(async () => { await save(); });
    await tab.reload(); await tab.waitForSelector('.nav-item');
    assert.equal(await tab.locator(`[data-retirement="${id}"]`).count(), 0);
    await tab.evaluate(() => { state.week = state.totalWeeks; G.nextSeason(state); render(); });
    assert(await tab.locator(`[data-retirement="${id}"]`).isVisible());
    await tab.evaluate(async () => { await save(); });
    await tab.reload(); await tab.waitForSelector('.nav-item');
    await tab.evaluate(id => profile(id), id);
    await tab.locator(`#modal [data-retirement="${id}"]`).click();
    await tab.locator(`[data-retirement-approve="${id}"]`).click();
    assert(await tab.evaluate(id => G.player(state,id).retired, id));
    await tab.evaluate(async () => { await save(); });
    await tab.reload(); await tab.waitForSelector('.nav-item');
    await tab.evaluate(id => profile(id), id);
    assert(await tab.locator('#modal').getByText('은퇴한 선수입니다.',{exact:false}).isVisible());
    assert.equal(await tab.locator('#modal [data-negotiate], #modal [data-scout]').count(), 0);
    assert(await tab.evaluate(() => G.validSave(state)));
    assert.deepEqual(errors, []);
    console.log('PASS: desktop/mobile inbox and profile actions, approval/deferral and IndexedDB reload.');
  } finally { if (browser) await browser.close(); await new Promise(r => server.close(r)); }
}
