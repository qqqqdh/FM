'use strict';
const assert = require('node:assert/strict'), G = require('./engine.js');
const s = G.newGame(42);
const buyer = s.clubs.find(c => c.id > 0 && s.leagues[c.league].flag === 'EN' && s.leagues[c.league].tier === 1);
const next = n => (Math.imul(n,1664525)+1013904223) >>> 0;
let seed = 0;
while (1 + Math.floor(next(seed)/4294967296*(s.clubs.length-1)) !== buyer.id) seed++;
const seller = s.clubs[1 + Math.floor(next(next(seed))/4294967296*(s.clubs.length-1))];
assert.notEqual(seller.id,buyer.id);
const star = G.roster(s,seller.id).find(p => p.pos === 'FW');
Object.assign(star,{name:'AI 슈퍼스타',position:'ST',atk:92,def:92,tech:92,pace:92,age:23,potential:110,salary:.2});
seller.tactics.formation='4-3-3'; seller.lineup=G.autoLineup(s,seller.id);
assert(seller.lineup.includes(star.id),'test player is a starter above the former OVR 86 limit');
buyer.tactics.formation='4-3-3';
G.roster(s,buyer.id).filter(p=>p.pos==='FW').forEach(p=>Object.assign(p,{atk:60,def:60,tech:60,pace:60}));
let id = Math.max(...s.players.map(p=>p.id),...s.academy.map(p=>p.id));
while(G.roster(s,buyer.id).length<25)s.players.push({...G.roster(s,buyer.id).find(p=>p.pos==='FW'),id:++id});
const budget=G.clubMarketCapacity(s,buyer).budget;
assert(budget>=G.value(star));
s.seed=seed;s.week=s.totalWeeks;
assert(G.advanceSummerWeek(s).ok);
assert(s.transfers.some(t=>t.text.includes(`AI 슈퍼스타: ${seller.name} → ${buyer.name}`)));
assert(G.roster(s,buyer.id).length<=25);
assert(G.clubMarketCapacity(s,buyer).budget<budget);
assert(G.validSave(JSON.parse(JSON.stringify(s))));
console.log('PASS: a full AI squad replaces a weaker player with an affordable OVR 92 starter');
